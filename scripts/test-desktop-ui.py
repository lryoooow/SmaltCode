class Model(BaseHTTPRequestHandler):
    def log_message(self, *args): pass
    def do_POST(self):
        body = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
        requests.append(body)
        messages = body["messages"]
        prompt = next((m.get("content", "") for m in reversed(messages) if m["role"] == "user"), "")
        if "验证失败状态" in str(prompt):
            self.send_response(401); self.send_header("Content-Type", "application/json"); self.end_headers()
            self.wfile.write(b'{"error":{"message":"test authentication failure"}}'); return
        self.send_response(200); self.send_header("Content-Type", "text/event-stream"); self.end_headers()
        def emit(delta, finish=None):
            self.wfile.write(("data: " + json.dumps({"choices":[{"delta":delta,"finish_reason":finish}]}, ensure_ascii=False) + "\n\n").encode("utf-8")); self.wfile.flush()
        def tool(name, args):
            emit({"tool_calls":[{"index":0,"id":"call_" + str(len(requests)),"function":{"name":name,"arguments":json.dumps(args, ensure_ascii=False)}}]}, "tool_calls")
        try:
            if not body.get("tools"): emit({"content":"OK"}, "stop")
            elif "准备多标签验收资料" in str(prompt):
                last_user = max(i for i,m in enumerate(messages) if m['role'] == 'user')
                n = sum(m['role'] == 'tool' for m in messages[last_user+1:])
                if n == 0: tool('write', {'path':'片段资料.md','content':'# 选区资料\n\n保留内容甲\n选区原文唯一\n保留内容乙\n\n' + '\n'.join('记录 '+str(i)+'：保留这些资料。' for i in range(80))})
                elif n == 1: tool('write', {'path':'第二份资料.md','content':'# 第二份资料\n\n' + '\n'.join('另一份记录 '+str(i) for i in range(80))})
                else: emit({'content':'多标签验收资料已保存'},'stop')
            elif "验证选区修改" in str(prompt):
                assert '选区原文唯一' in str(prompt) and '"selection":true' in str(prompt)
                last_user = max(i for i,m in enumerate(messages) if m['role'] == 'user')
                n = sum(m['role'] == 'tool' for m in messages[last_user+1:])
                if n == 0: tool('apply_patch', {'patch':'*** Begin Patch\n*** Update File: 片段资料.md\n@@\n 保留内容甲\n-选区原文唯一\n+选区修改完成\n 保留内容乙\n*** End Patch'})
                else: emit({'content':'选区修改已完成，其余资料保持原样'},'stop')
            elif "验证上下文引用" in str(prompt):
                assert '用户引用的文件资料' in str(prompt) and '会议记录.txt' in str(prompt)
                assert '会议：完成前端接入' in str(prompt)
                emit({'content':'已收到用户明确引用的会议记录'},'stop')
            elif "验证任务中心后台" in str(prompt):
                emit({'content':'后台工作持续进行。\n\n'})
                i=0
                while not activity_continue.wait(.1):
                    emit({'content':'后台节点 '+str(i)+' 已推进。\n\n'}); i+=1
                emit({'content':'任务中心后台工作已完成'},'stop')
            elif "验证任务中心审批" in str(prompt):
                last_user = max(i for i,m in enumerate(messages) if m['role'] == 'user')
                n = sum(m['role'] == 'tool' for m in messages[last_user+1:])
                if n == 0: tool('shell', {'command':'echo activity-center-approved'})
                else: emit({'content':'任务中心待办已处理'},'stop')
            elif "验证停止" in str(prompt):
                emit({"content":"正在进行耗时任务…"})
                time.sleep(8)
                emit({"content":"此消息不应在停止后到达"}, "stop")
            elif "验证项目与批量审批" in str(prompt):
                n = len([m for m in messages if m["role"] == "tool"])
                if n == 0:
                    assert any("PROJECT_CONTEXT_UNIQUE" in str(m.get("content")) for m in messages if m["role"] == "system")
                    emit({"tool_calls":[{"index":i,"id":"batch_" + str(len(requests)) + "_" + str(i),"function":{"name":"write","arguments":json.dumps({"path":"group-" + str(i) + ".txt","content":"分组审批实际文件"},ensure_ascii=False)}} for i in range(3)]},"tool_calls")
                else: emit({"content":"项目批量操作已完成"},"stop")
            elif "验证类别审批" in str(prompt):
                n = len([m for m in messages if m["role"] == "tool"])
                if n < 3: tool("write", {"path":"category-" + str(n) + ".txt","content":"同类操作只确认一次"})
                else: emit({"content":"同类审批已完成"},"stop")
            elif "验证运行中权限" in str(prompt):
                n = len([m for m in messages if m["role"] == "tool"])
                if n < 2: tool("write", {"path":"live-permission-" + str(n) + ".txt","content":"运行中调整权限"})
                else: emit({"content":"权限切换已生效"},"stop")
            elif "验证无步数限制" in str(prompt):
                n = len([m for m in messages if m["role"] == "tool"])
                if n < 64: tool("plan", {"steps":[{"content":"长任务步骤 " + str(n + 1),"status":"inProgress"}]})
                else: emit({"content":"已连续完成64个工具步骤"},"stop")
            elif "验证过程折叠" in str(prompt):
                n = len([m for m in messages if m["role"] == "tool"])
                if n == 0:
                    emit({"reasoning_content":"先核对资料，然后执行检查并保存结果。"})
                    tool("read", {"path":"会议记录.txt"})
                elif n == 1:
                    emit({"reasoning_content":"资料已读取，检查实际输出后再写入文件。"})
                    tool("shell", {"command":"node progress-probe.cjs"})
                elif n == 2:
                    emit({"reasoning_content":"检查完成，开始保存结果。"})
                    tool("write", {"path":"progress-result.md","content":"# 过程检查完成\n实际输出已核对。\n"})
                else: emit({"content":"资料核对、执行检查和文件保存都已完成。"},"stop")
            elif "验证节点回复" in str(prompt):
                n = len([m for m in messages if m["role"] == "tool"])
                if n == 0:
                    emit({"reasoning_content":"先核对真实资料。"})
                    emit({"content":"正在核对资料，随后保存整理结果。"})
                    tool("read", {"path":"会议记录.txt"})
                elif n == 1:
                    emit({"content":"资料已经核对，开始保存整理结果。"})
                    tool("write", {"path":"milestone-result.txt","content":"节点说明验收完成。"})
                else: emit({"content":"整理结果已保存。"},"stop")
            elif "验证运行中自由浏览" in str(prompt):
                n = len([m for m in messages if m["role"] == "tool"])
                if n == 0:
                    tool("write", {"path":"自由浏览资料.md","content":"# 自由浏览资料\n\n" + "\n\n".join("文件记录 " + str(i) + "：运行中也能独立浏览文件内容。" for i in range(80))})
                else:
                    emit({"content":"\n\n".join("历史节点 " + str(i) + "：已读取资料，正在持续处理任务。" for i in range(80)) + "\n\n"})
                    i = 0
                    while not scroll_continue.wait(.1):
                        emit({"content":"实时节点 " + str(i) + "：后台继续执行。\n\n"}); i += 1
                    emit({"content":"任务已完成，自由浏览没有中断执行。"},"stop")
            elif "验证托盘驻留" in str(prompt):
                emit({"content":"后台任务开始"})
                time.sleep(1.5)
                emit({"content":"，窗口关闭后仍然完成"},"stop")
            elif "验证拒绝" in str(prompt):
                if messages[-1]["role"] != "tool": tool("shell", {"command":"echo should-not-run"})
                else: emit({"content":"已尊重拒绝，没有执行该命令。"}, "stop")
            else:
                tools = [m for m in messages if m["role"] == "tool"]
                n = len(tools)
                if n == 0:
                    emit({"reasoning_content":"先读取会议记录，再生成可核验的文件。"})
                    tool("plan", {"steps":[{"content":"读取会议记录","status":"inProgress"},{"content":"生成说明并更新索引","status":"pending"}]})
                elif n == 1: tool("read", {"path":"会议记录.txt"})
                elif n == 2: tool("shell", {"command":"echo ui-live-output"})
                elif n == 3: tool("ask_user", {"question":"产物使用哪种语言？","options":["中文","English"]})
                elif n == 4: tool("write", {"path":"deliverables/周报说明.md","content":"# 本周工作说明\n\n完成前端接入，验证审批与文件预览。\n\n| 项目 | 结果 |\n|---|---|\n| UI | 已接入 |\n"})
                elif n == 5: tool("apply_patch", {"patch":"*** Begin Patch\n*** Update File: README.md\n@@\n # 项目资料\n-待整理\n+已经整理，可查看 deliverables/周报说明.md\n*** Add File: deliverables/检查结果.txt\n+文件预览与审批验证通过。\n*** End Patch"})
                else:
                    text = "已完成 **周报说明**，并更新了项目索引。\n\n| 文件 | 用途 |\n|---|---|\n| 周报说明.md | 工作说明 |\n| 检查结果.txt | 验证记录 |\n\n```text\n真实文件已保存到工作文件夹。\n```"
                    for i in range(0, len(text), 5):
                        emit({"content":text[i:i+5]}); time.sleep(.025)
                    emit({}, "stop")
            self.wfile.write(b'data: {"choices":[],"usage":{"prompt_tokens":240,"completion_tokens":60}}\n\ndata: [DONE]\n\n'); self.wfile.flush()
        except (BrokenPipeError, ConnectionResetError, ConnectionAbortedError): pass

